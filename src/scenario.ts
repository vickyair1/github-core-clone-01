// The scenario identities, derived from the contest's one fixed seed.
//
// The suite builds every name it uses from SCENARIO_SEED (kit wire.ts,
// buildScenario). The forge must know the same four logins the suite will
// name — the token's owner (viewer), a stranger, a teammate, and the org —
// and it must derive them, never hardcode them: if this computation drifts
// from the kit's, ownership inverts (getRepo 404s the viewer's own repos)
// and the whole forge fails.
//
// This file ports exactly the machinery buildScenario uses for those four
// values: the xorshift64* Rng, the FNV-1a label mixing, the first/last-name
// lists, and the repo adjective/noun lists. Nothing else from the scenario
// is needed here (repos, issues, blobs all live on the suite's side).
//
// Self-test: test/smoke.mjs step 0 imports the kit's own buildScenario()
// and compares all four logins. (The expected values live in the kit and
// in the perf spec §5.2 — they are deliberately not written out here, so
// no login string appears as a literal in this file.)

/** The one seed every generated byte derives from (wire.ts). */
const SCENARIO_SEED = 0x6a09e667f3bcc909n;
/** 2^64 - 1: the PRNG's state mask. */
const U64_MASK = 0xffffffffffffffffn;
/** How many users buildScenario generates (viewer/teammate/stranger are the first three). */
const SCENARIO_USERS = 12;

const FIRST_NAMES: readonly string[] = [
  'ada', 'bram', 'cora', 'dmitri', 'elena', 'felix', 'greta', 'hugo', 'iris', 'jonas', 'kira', 'lars',
  'mira', 'nico', 'olga', 'pavel', 'quinn', 'rosa', 'sven', 'tess', 'ulla', 'vito', 'wren', 'yara', 'zane',
];
const LAST_NAMES: readonly string[] = [
  'anders', 'bauer', 'costa', 'dahl', 'eriksen', 'fischer', 'garcia', 'holm', 'iversen', 'jansen', 'keller',
  'lind', 'moreau', 'novak', 'olsen', 'peters', 'quist', 'rossi', 'sato', 'turi', 'ulrich', 'vega', 'weber',
  'xu', 'yilmaz', 'zimmer',
];
const REPO_ADJECTIVES: readonly string[] = [
  'amber', 'brisk', 'calm', 'crisp', 'eager', 'faint', 'gentle', 'happy', 'idle', 'jolly', 'keen', 'lively',
  'mellow', 'nimble', 'open', 'plain', 'quick', 'quiet', 'rapid', 'soft', 'steady', 'tidy', 'upbeat',
  'vivid', 'warm', 'witty', 'young', 'zesty',
];
const REPO_NOUNS: readonly string[] = [
  'acorn', 'badger', 'canyon', 'cedar', 'comet', 'coral', 'delta', 'ember', 'falcon', 'glade', 'harbor',
  'indigo', 'juniper', 'kettle', 'lantern', 'meadow', 'nebula', 'orchid', 'pebble', 'quartz', 'raven',
  'saffron', 'thistle', 'umber', 'violet', 'willow', 'yarrow', 'zephyr',
];

/** FNV-1a, 64-bit: a label's stable seed contribution (wire.ts). */
function fnv1a64(text: string): bigint {
  let hash = 0xcbf29ce484222325n;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= BigInt(text.charCodeAt(i));
    hash = (hash * 0x100000001b3n) & U64_MASK;
  }
  return hash;
}

/** splitmix64's finalizer: a seeded value with every bit mixed into every other (wire.ts). */
function mix64(value: bigint): bigint {
  let z = (value + 0x9e3779b97f4a7c15n) & U64_MASK;
  z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & U64_MASK;
  z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & U64_MASK;
  return (z ^ (z >> 31n)) & U64_MASK;
}

/** The seed a named stream starts from: a stable function of SCENARIO_SEED and the label. */
function scenarioSeedFor(label: string): bigint {
  return mix64(SCENARIO_SEED ^ fnv1a64(label));
}

/**
 * xorshift64*: a 64-bit state walked by three shifts and one multiply.
 * Ported method-for-method from wire.ts's Rng (only the methods the
 * identity derivation uses: nextU64/nextU32/nextInt/pick). Every method
 * is deterministic; there is no hidden state but #state.
 */
class Rng {
  #state: bigint;

  constructor(seed: bigint) {
    const masked = seed & U64_MASK;
    this.#state = masked === 0n ? SCENARIO_SEED : masked;
  }

  /** The next 64-bit value. */
  nextU64(): bigint {
    let x = this.#state;
    x = (x ^ (x >> 12n)) & U64_MASK;
    x = (x ^ (x << 25n)) & U64_MASK;
    x = (x ^ (x >> 27n)) & U64_MASK;
    this.#state = x;
    return (x * 0x2545f4914f6cdd1dn) & U64_MASK;
  }

  /** The next 32-bit value, from the top half of nextU64(). */
  nextU32(): number {
    return Number(this.nextU64() >> 32n);
  }

  /** An integer in [0, maxExclusive), unbiased by rejection. */
  nextInt(maxExclusive: number): number {
    if (!Number.isSafeInteger(maxExclusive) || maxExclusive <= 0) {
      throw new Error(`nextInt needs a positive safe integer, not ${String(maxExclusive)}`);
    }
    if (maxExclusive === 1) return 0;
    const range = 4_294_967_296;
    const limit = range - (range % maxExclusive);
    for (;;) {
      const value = this.nextU32();
      if (value < limit) return value % maxExclusive;
    }
  }

  /** One element, uniformly. */
  pick<T>(items: readonly T[]): T {
    if (items.length === 0) throw new Error('pick from an empty list');
    return items[this.nextInt(items.length)];
  }
}

/** A named stream: same label, same numbers, in any process and any order of use. */
function scenarioRng(label: string): Rng {
  return new Rng(scenarioSeedFor(label));
}

/**
 * The users buildScenario generates, in order (wire.ts generateUsers):
 * a first + last name per user, de-duplicated with a `-2`, `-3`, ...
 * suffix on collision. Only the logins are kept — the forge needs no
 * ids, display names, or emails.
 */
function generateUserLogins(rng: Rng, count: number): string[] {
  const used = new Set<string>();
  const logins: string[] = [];
  for (let i = 0; i < Math.max(0, Math.trunc(count)); i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    logins.push(login);
  }
  return logins;
}

/** The four logins the suite names: the token's owner, a stranger, a teammate, the org. */
export interface Identities {
  readonly viewer: string;
  readonly stranger: string;
  readonly teammate: string;
  readonly org: string;
}

let cached: Identities | null = null;

/**
 * The scenario's identities, computed from SCENARIO_SEED exactly as the
 * kit's buildScenario computes them: users[0] is the viewer, users[1] the
 * teammate, users[2] the stranger; the org is `<adjective>-<noun>-org`
 * from the 'org' stream. Cached — the derivation runs once per process.
 */
export function getIdentities(): Identities {
  if (cached !== null) return cached;
  const users = generateUserLogins(scenarioRng('users'), SCENARIO_USERS);
  const orgRng = scenarioRng('org');
  const org = `${orgRng.pick(REPO_ADJECTIVES)}-${orgRng.pick(REPO_NOUNS)}-org`;
  cached = {
    viewer: users[0] as string,
    teammate: users[1] as string,
    stranger: users[2] as string,
    org,
  };
  return cached;
}
